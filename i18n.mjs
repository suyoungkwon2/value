export function localizeValues(lang='en') {
  return VALUES.map(value=>lang==='ko'?{...value,...KO_VALUES[value.id]}:{...value});
}
export function localizeItems(items,version,lang='en') {
  if(lang!=='ko') return items.map(item=>({...item}));
  return items.map(item=>{
    const translated=version==='detailed'?KO_DETAILED[item.id-1]:KO_VALUES[item.id];
    if(!translated) throw new RangeError('Missing survey translation.');
    return {...item,...(Array.isArray(translated)?{name:translated[0],description:translated[1]}:{name:translated.name,description:translated.description})};
  });
}
export function localizeResult(result,lang='en') {
  return {...result,values:result.values.map(value=>({...value,...(lang==='ko'?KO_VALUES[value.id]:VALUES.find(source=>source.id===value.id))}))};
}
